// Turns per-pixel masks into SVG path data with potrace and writes the
// generated terrain module the meadow scene draws from.

import { writeFile } from 'node:fs/promises'
import potrace from 'potrace'
import sharp from 'sharp'

const round = (n, decimals = 1) => Math.round(n * 10 ** decimals) / 10 ** decimals

async function trace(mask, frame, decimals = 1) {
  const { width: w, height: h, x0, y0, scale = 1 } = frame
  if (!mask.some((v) => v)) return ''
  const px = Buffer.alloc(w * h, 255)
  mask.forEach((v, i) => v && (px[i] = 0))
  const png = await sharp(px, { raw: { width: w, height: h, channels: 1 } }).png().toBuffer()
  const tracer = new potrace.Potrace({ turdSize: 10 * scale * scale, optTolerance: 0.5, alphaMax: 1, threshold: 128 })
  await new Promise((res, rej) => tracer.loadImage(png, (err) => (err ? rej(err) : res())))
  const d = tracer.getPathTag().match(/ d="([^"]*)"/)?.[1] ?? ''
  // Back into frame units, one decimal place
  return d
    .replace(/(-?\d*\.?\d+)[ ,]+(-?\d*\.?\d+)/g, (_, x, y) => `${round(+x / scale + x0, decimals)} ${round(+y / scale + y0, decimals)}`)
    .replace(/\s+/g, ' ')
    .trim()
}

export async function emitModule(out, { source, frame, skyline, facets, trees, groups = [], camera, ...extra }) {
  const { x0, scale = 1 } = frame

  const traced = []
  for (const f of facets) {
    const d = await trace(f.mask, frame, f.decimals ?? 1)
    if (d) traced.push({ kind: f.kind, ...(f.n ? { n: f.n.map((v) => Math.round(v * 1000) / 1000) } : { tone: f.tone }), haze: round(f.haze * 10) / 10, d })
  }

  const step = 2
  const sky = []
  for (let x = 0; x < skyline.length; x += step * scale) sky.push(round(skyline[x]))

  const body = `// Generated by scripts/meadow from ${source}. Do not edit by hand.
import type { TerrainData } from './terrain-types'

export const TERRAIN: TerrainData = ${JSON.stringify(
    { source, x0, step, skyline: sky, facets: traced, groups: groups.map((n) => n.map((v) => Math.round(v * 1000) / 1000)), trees, camera, ...extra },
    null,
    1,
  )
    .replace(/\n\s*/g, ' ')
    .replace(/"(\w+)":/g, '$1:')}
`
  await writeFile(out, body)
  console.log(`wrote ${out}: ${(body.length / 1024).toFixed(0)} KB, ${traced.length} facets`)
}
