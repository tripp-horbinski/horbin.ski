// Turns per-pixel masks into SVG path data with potrace and writes the
// generated terrain module the meadow scene draws from.

import { writeFile } from 'node:fs/promises'
import potrace from 'potrace'
import sharp from 'sharp'

// Where each Flatiron's tip sits in the 1200×800 reference frame; rock blobs
// nearest these become the named, clickable slabs
const SLAB_TIPS = { first: [692, 194], second: [597, 238], third: [456, 250], fourth: [346, 278], fifth: [292, 284] }

const round = (n, decimals = 1) => Math.round(n * 10 ** decimals) / 10 ** decimals

async function trace(mask, frame, decimals = 1) {
  const { width: w, height: h, x0, y0, scale = 1 } = frame
  if (!mask.some((v) => v)) return ''
  const px = Buffer.alloc(w * h, 255)
  mask.forEach((v, i) => v && (px[i] = 0))
  const png = await sharp(px, { raw: { width: w, height: h, channels: 1 } }).png().toBuffer()
  const tracer = new potrace.Potrace({ turdSize: 10 * scale * scale, optTolerance: 0.5, alphaMax: 1, threshold: 128 })
  await new Promise((res, rej) => tracer.loadImage(png, (err) => (err ? rej(err) : res())))
  const d = tracer.getPathTag().match(/ d="([^"]*)"/)?.[1] ?? ''
  // Back into frame units, one decimal place
  return d
    .replace(/(-?\d*\.?\d+)[ ,]+(-?\d*\.?\d+)/g, (_, x, y) => `${round(+x / scale + x0, decimals)} ${round(+y / scale + y0, decimals)}`)
    .replace(/\s+/g, ' ')
    .trim()
}

// 8-connected blobs, each with its pixel count and topmost pixel
function components(mask, w, h) {
  const label = new Int32Array(w * h).fill(-1)
  const blobs = []
  const stack = []
  for (let i = 0; i < w * h; i++) {
    if (!mask[i] || label[i] >= 0) continue
    const blob = { id: blobs.length, size: 0, top: [i % w, (i / w) | 0] }
    blobs.push(blob)
    label[i] = blob.id
    stack.push(i)
    while (stack.length) {
      const j = stack.pop()
      const x = j % w
      const y = (j / w) | 0
      blob.size++
      if (y < blob.top[1]) blob.top = [x, y]
      for (let dy = -1; dy <= 1; dy++) {
        for (let dx = -1; dx <= 1; dx++) {
          const nx = x + dx
          const ny = y + dy
          const k = ny * w + nx
          if (nx >= 0 && ny >= 0 && nx < w && ny < h && mask[k] && label[k] < 0) {
            label[k] = blob.id
            stack.push(k)
          }
        }
      }
    }
  }
  return { label, blobs }
}

export async function emitModule(out, { source, frame, skyline, facets, rock, trees, groups = [], camera, ...extra }) {
  const { width: w, height: h, x0, y0, scale = 1 } = frame

  const traced = []
  for (const f of facets) {
    const d = await trace(f.mask, frame, f.decimals ?? 1)
    if (d) traced.push({ kind: f.kind, ...(f.n ? { n: f.n.map((v) => Math.round(v * 1000) / 1000) } : { tone: f.tone }), haze: round(f.haze * 10) / 10, d })
  }

  // Name the big slabs by matching blobs to the known tips
  const { label, blobs } = components(rock, w, h)
  const toFrame = ([x, y]) => [x / scale + x0, y / scale + y0]
  const taken = new Set()
  const slabs = []
  for (const [id, tip] of Object.entries(SLAB_TIPS)) {
    let best = null
    for (const b of blobs) {
      if (b.size < 60 * scale * scale || taken.has(b.id)) continue
      const [tx, ty] = toFrame(b.top)
      const dist = Math.hypot(tx - tip[0], ty - tip[1]) - Math.sqrt(b.size) / scale / 4
      if (!best || dist < best.dist) best = { b, dist }
    }
    if (!best) continue
    taken.add(best.b.id)
    const mask = new Uint8Array(w * h)
    label.forEach((l, i) => l === best.b.id && (mask[i] = 1))
    slabs.push({ id, d: await trace(mask, frame), top: toFrame(best.b.top).map(round) })
  }

  const step = 2
  const sky = []
  for (let x = 0; x < skyline.length; x += step * scale) sky.push(round(skyline[x]))

  const body = `// Generated by scripts/meadow from ${source}. Do not edit by hand.
import type { TerrainData } from './terrain-types'

export const TERRAIN: TerrainData = ${JSON.stringify(
    { source, x0, step, skyline: sky, facets: traced, slabs, groups: groups.map((n) => n.map((v) => Math.round(v * 1000) / 1000)), trees, camera, ...extra },
    null,
    1,
  )
    .replace(/\n\s*/g, ' ')
    .replace(/"(\w+)":/g, '$1:')}
`
  await writeFile(out, body)
  console.log(`wrote ${out}: ${(body.length / 1024).toFixed(0)} KB, ${traced.length} facets, slabs ${slabs.map((s) => s.id).join(' ')}`)
}
